// 第三章 06 多维数组

// 一维数组: [1, 2, 3, 4, 5]
// 二维数组：[[1, 2, 3], [4, 5, 6], [7, 8, 9]]
// 三维数组：[[[1, 2], [3, 4]], [[5, 6], [7, 8]]]
// 故多维数组:对数组进行嵌套,即数组内的每个元素依旧是数组

// 语法: 数据类型 数组名[维度1][维度2]...[维度n];

// 写法1:
// int v[3][3];
// v[0]v[0] = 11;
// v[0][1] = 12;
// v[1][0] = 21;
// ...

// 写法2:
// int v[3][3] = {{11, 12, 13},
//                 {14, 15, 16},
//                 {17, 18, 19}};

#include <iostream>

int main(){

    // 二维数组
    int v[2][2] = {{11, 12},
                    {14, 15}};
    
    std::cout << v[0][0] << std::endl;
    std::cout << v[0][1] << std::endl;
    std::cout << v[1][0] << std::endl;
    std::cout << v[1][1] << std::endl;
    std::cout << std::endl;


    // 三维数组
    int v2[2][2][2] = {{{11, 12},
                        {13, 14}},
                        {{21, 22},
                        {23, 24}}};
    
    std::cout << v2[0][0][0] << std::endl;
    std::cout << v2[0][0][1] << std::endl;
    std::cout << v2[0][1][0] << std::endl;
    std::cout << v2[0][1][1] << std::endl;
    std::cout << v2[1][0][0] << std::endl;
    std::cout << v2[1][0][1] << std::endl;
    std::cout << v2[1][1][0] << std::endl;
    std::cout << v2[1][1][1] << std::endl;


    return 0;
}