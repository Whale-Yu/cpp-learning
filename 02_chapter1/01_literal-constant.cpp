// 第一章 01-字面常量

// 常量：在程序执行过程中值不会改变的量

// 常量分为 字面常量 和 符号常量

// 字面常量: 被书写到代码内的常量,也称字面量

#include <iostream>

int main() {
    // 整形字面常量:整数, 不带小数点的数字
    21;

    // 实型字面常量:浮点数, 带小数点的数字
    3.14; 

    // 以上两种都是数值型常量

    // 字符字面常量:单个字符, 用单引号括起来
    'c'; 

    // 字符串字面常量:一串字符, 用双引号括起来
    "hello"; 

    std::cout << 21 << std::endl;
    std::cout << 3.14 << std::endl;
    std::cout << 'c' << std::endl;
    std::cout << "hello" << std::endl;

    return 0;
}